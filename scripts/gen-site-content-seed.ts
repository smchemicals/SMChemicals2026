import { readFileSync, writeFileSync } from "node:fs";
import { defaultHome, defaultContact } from "../data/content";
import { defaultAbout } from "../data/about";
import { defaultCareers } from "../data/careers";

/*
 * Writes supabase/migrations/0004_site_content.sql from the defaults in data/*.ts, so the database starts with exactly what
 * the site shows and every section starts "Up to date" in the admin's Publish page.
 * Run:  npx tsx scripts/gen-site-content-seed.ts
 */
const lit = (o: unknown) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;
const sections: [string, unknown][] = [
	["home", defaultHome],
	["contact", defaultContact],
	["about", defaultAbout],
	["careers", defaultCareers],
];

const productsBlock = readFileSync("scripts/seed-blocks/products-snapshot.sql", "utf8");

const out = [
	"-- 0004 site content: Home, Contact, About and Careers, and the first published copy of the catalogue.",
	"-- GENERATED by scripts/gen-site-content-seed.ts from data/*.ts. Needs 0001 to 0003.",
	"-- Nothing here overwrites content that already exists, so it is safe to re-run later.",
	"",
	"-- The content as the admin edits it (the draft) ...",
	"insert into public.site_settings (key, value) values",
	sections.map(([k, v]) => `  ('${k}', ${lit(v)})`).join(",\n"),
	"on conflict (key) do nothing;",
	"",
	"-- ... and the same as published, which is what the website reads. Every section therefore starts as up to date.",
	"insert into public.page_snapshots (page, data, raw)",
	"select key, value, value from public.site_settings where key in ('home', 'contact', 'about', 'careers')",
	"on conflict (page) do nothing;",
	"",
	productsBlock,
].join("\n");

writeFileSync("supabase/migrations/0004_site_content.sql", out);
console.log("wrote supabase/migrations/0004_site_content.sql");
